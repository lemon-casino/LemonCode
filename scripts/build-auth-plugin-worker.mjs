import { build } from "esbuild";
import { format } from "oxfmt";
import { readFile, readdir, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
  preserveQoderCacheUsage,
  preserveTraeCacheUsage,
} from "../packages/provider-node/src/provider-auth/plugins/vendor-cache-usage-patch.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const folder = resolve(root, "packages/provider-node/src/provider-auth/plugins");
const vendor = resolve(folder, "../vendor");

// 修复：shared 协议也会进入 Worker；暴露只读生成路径，让发行回归发现遗漏的生成产物。
export async function generateAuthPluginWorkerSource() {
  const manifest = JSON.parse(await readFile(resolve(vendor, "manifest.json"), "utf8"));
  const notices = new Set([await readFile(resolve(vendor, "LICENSE"), "utf8")]);
  // The worker also embeds the native Google protocol adaptation, which retains Magpie's MIT notice.
  notices.add(await readFile(resolve(folder, "../native/LICENSE.magpie"), "utf8"));
  for (const pkg of manifest.packages) {
    for (const source of pkg.files) {
      const bytes = await readFile(resolve(vendor, pkg.directory, source.file));
      if (createHash("sha256").update(bytes).digest("hex") !== source.sha256)
        throw new Error(`Pinned plugin source changed: ${pkg.directory}/${source.file}`);
    }
    for (const name of await readdir(resolve(vendor, pkg.directory)))
      if (name.startsWith("LICENSE"))
        notices.add(await readFile(resolve(vendor, pkg.directory, name), "utf8"));
  }
  const result = await build({
    entryPoints: [resolve(folder, "worker.mjs")],
    bundle: true,
    platform: "node",
    target: "node24",
    format: "cjs",
    write: false,
    minify: true,
    legalComments: "inline",
    plugins: [
      {
        name: "pinned-plugin-source",
        setup(api) {
          api.onResolve({ filter: /\.mjs\.source$/ }, (args) => ({
            path: resolve(args.resolveDir, args.path),
            namespace: "vendor",
          }));
          api.onResolve({ filter: /^\.\//, namespace: "vendor" }, (args) => ({
            path: resolve(dirname(args.importer), args.path + ".source"),
            namespace: "vendor",
          }));
          api.onLoad({ filter: /.*/, namespace: "vendor" }, async (args) => {
            const source = await readFile(args.path, "utf8");
            return {
              contents:
                args.path === resolve(vendor, "qoder/index.mjs.source")
                  ? preserveQoderCacheUsage(source)
                  : args.path === resolve(vendor, "trae/index.mjs.source")
                    ? preserveTraeCacheUsage(source)
                    : source,
              loader: "js",
              resolveDir: dirname(args.path),
            };
          });
        },
      },
    ],
  });
  const source = `/*! @license Generated by scripts/build-auth-plugin-worker.mjs. Do not edit.\nSource: ${manifest.repository} @ ${manifest.revision}\n${[...notices].join("\n\n")}\n*/\nexport const PLUGIN_WORKER_SOURCE: string = ${JSON.stringify(result.outputFiles[0].text)};\n`;
  const formatted = await format("worker-source.ts", source);
  if (formatted.errors.length) throw new Error("Generated worker source could not be formatted");
  return { source: formatted.code, workerBytes: result.outputFiles[0].text.length };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { source, workerBytes } = await generateAuthPluginWorkerSource();
  await writeFile(resolve(folder, "worker-source.ts"), source);
  process.stdout.write(`Embedded plugin worker: ${workerBytes} bytes\n`);
}
