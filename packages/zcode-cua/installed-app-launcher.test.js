test("Windows rejects normalized ambiguity without starting either candidate", async () => {
  const calls = [];
  const launcher = createInstalledAppLauncher({
    platform: "win32",
    async run(command) {
      calls.push(command);
      return {
        stdout: JSON.stringify([
          { Name: "ChatLauncher", AppID: "chat-one" },
          { Name: "ChatScLauncher", AppID: "chat-two" },
        ]),
        stderr: "",
      };
    },
  });

  await assert.rejects(launcher.launch({ name: "Chat" }), (error) => {
    assert.ok(error instanceof InstalledAppLauncherError);
    assert.equal(error.code, "AMBIGUOUS_APP");
    return true;
  });
  assert.equal(calls.length, 1);
});

