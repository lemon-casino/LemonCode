test("reports missing installations and command failures with stable codes", async () => {
  const missing = createInstalledAppLauncher({
    platform: "win32",
    async run() {
      return { stdout: "[]", stderr: "" };
    },
  });
  await assert.rejects(missing.launch({ name: "Missing" }), { code: "APP_NOT_FOUND" });

  const failed = createInstalledAppLauncher({
    platform: "win32",
    async run(command) {
      if (command.file === "powershell.exe") {
        return {
          stdout: JSON.stringify({ Name: "Example", AppID: "example" }),
          stderr: "",
        };
      }
      throw new Error("start failed");
    },
  });
  await assert.rejects(failed.launch({ name: "Example" }), { code: "LAUNCH_FAILED" });
});

test("macOS resolves bundle metadata and launches through open without a shell", async () => {
  const calls = [];
  const launcher = createInstalledAppLauncher({
    platform: "darwin",
    async run(command) {
      calls.push(command);
      if (command.file === "/usr/bin/mdfind") {
        return { stdout: "/Applications/Example.app\0", stderr: "" };
      }
      if (command.file === "/usr/bin/mdls") {
        const field = command.args[1];
        return {
          stdout: field === "kMDItemCFBundleIdentifier" ? "com.example.app\n" : "Example\n",
          stderr: "",
        };
      }
      return { stdout: "", stderr: "" };
    },
  });

  await launcher.launch({ bundle_id: "com.example.app" });
  assert.deepEqual(calls.at(-1).file, "/usr/bin/open");
  assert.deepEqual(calls.at(-1).args, ["-b", "com.example.app"]);
});

test("Linux parses XDG desktop entries and passes the file as a gio argument", async () => {
  const root = await mkdtemp(join(tmpdir(), "zcode-cua-launcher-"));
  try {
    const applications = join(root, "applications");
    await mkdir(applications);
    const desktopFile = join(applications, "example.desktop");
    await writeFile(
      desktopFile,
      "[Desktop Entry]\nType=Application\nName=Example\nExec=/opt/example/bin/example %U\n",
      "utf8",
    );
    const calls = [];
    const launcher = createInstalledAppLauncher({
      platform: "linux",
      env: { XDG_DATA_HOME: root, XDG_DATA_DIRS: "" },
      async run(command) {
        calls.push(command);
        return { stdout: "", stderr: "" };
      },
    });

    const app = await launcher.launch({ name: "example" });
    assert.equal(app.executable, "example");
    assert.equal(calls.length, 1);
    assert.equal(calls[0].file, "gio");
    assert.deepEqual(calls[0].args, ["launch", desktopFile]);
  } finally {
    await rm(root, { recursive: true, force: true });
  }
});

test("Linux resolves desktop-file bundle_id with user entries overriding system entries", async () => {
  const root = await mkdtemp(join(tmpdir(), "zcode-cua-launcher-priority-"));
  try {
    const userRoot = join(root, "user");
    const systemRoot = join(root, "system");
    const userApplications = join(userRoot, "applications");
    const systemApplications = join(systemRoot, "applications");
    await Promise.all([
      mkdir(userApplications, { recursive: true }),
      mkdir(systemApplications, { recursive: true }),
    ]);
    const userDesktopFile = join(userApplications, "example.desktop");
    await Promise.all([
      writeFile(
        userDesktopFile,
        "[Desktop Entry]\nType=Application\nName=Example User\nExec=/opt/user/example %U\n",
        "utf8",
      ),
      writeFile(
        join(systemApplications, "example.desktop"),
        "[Desktop Entry]\nType=Application\nName=Example System\nExec=/opt/system/example %U\n",
        "utf8",
      ),
    ]);
    const calls = [];
    const launcher = createInstalledAppLauncher({
      platform: "linux",
      env: { XDG_DATA_HOME: userRoot, XDG_DATA_DIRS: systemRoot },
      async run(command) {
        calls.push(command);
        return { stdout: "", stderr: "" };
      },
    });

    const app = await launcher.launch({ bundle_id: "example.desktop" });
    assert.equal(app.name, "Example User");
    assert.equal((await launcher.launch({ bundle_id: "example" })).name, "Example User");
    assert.equal(calls.length, 2);
    for (const call of calls) {
      assert.deepEqual(call, {
        file: "gio",
        args: ["launch", userDesktopFile],
        signal: call.signal,
      });
    }
  } finally {
    await rm(root, { recursive: true, force: true });
  }
});

test("Linux user Hidden entry suppresses the same system desktop-file id", async () => {
  const root = await mkdtemp(join(tmpdir(), "zcode-cua-launcher-hidden-"));
  try {
    const userRoot = join(root, "user");
    const systemRoot = join(root, "system");
    const userApplications = join(userRoot, "applications");
    const systemApplications = join(systemRoot, "applications");
    await Promise.all([
      mkdir(userApplications, { recursive: true }),
      mkdir(systemApplications, { recursive: true }),
    ]);
    await Promise.all([
      writeFile(
        join(userApplications, "example.desktop"),
        "[Desktop Entry]\nType=Application\nName=Example\nExec=/opt/user/example\nHidden=true\n",
        "utf8",
      ),
      writeFile(
        join(systemApplications, "example.desktop"),
        "[Desktop Entry]\nType=Application\nName=Example\nExec=/opt/system/example\n",
        "utf8",
      ),
    ]);
    const launcher = createInstalledAppLauncher({
      platform: "linux",
      env: { XDG_DATA_HOME: userRoot, XDG_DATA_DIRS: systemRoot },
      async run() {
        throw new Error("hidden desktop entry must not launch");
      },
    });

    await assert.rejects(launcher.launch({ bundle_id: "example.desktop" }), {
      code: "APP_NOT_FOUND",
    });
  } finally {
    await rm(root, { recursive: true, force: true });
  }
});
